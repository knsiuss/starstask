-- ---------------------------------------------------------------------------
-- Internal developer monitoring
--
-- Three append-only event tables and one aggregate read function. None of this
-- is exposed to the product UI: the tables have RLS enabled with no policies
-- and no grants for anon or authenticated, so only the service role (server
-- side) can read or write them. Existing audit_logs remain the app-wide audit
-- trail and are read with the service role as well.
-- ---------------------------------------------------------------------------
-- ---------------------------------------------------------------------------
-- auth_activity_events: successes and failures recorded by /auth/callback
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.auth_activity_events (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id uuid REFERENCES auth.users (id) ON DELETE SET NULL,
  event_type text NOT NULL,
  provider text,
  reason text,
  created_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT auth_activity_events_type_allowed CHECK (event_type IN ('sign_in_succeeded', 'sign_in_failed')),
  CONSTRAINT auth_activity_events_success_has_user CHECK (
    event_type <> 'sign_in_succeeded'
    OR user_id IS NOT NULL
  ),
  CONSTRAINT auth_activity_events_provider_format CHECK (
    provider IS NULL
    OR provider ~ '^[a-z][a-z0-9_]{1,31}$'
  ),
  CONSTRAINT auth_activity_events_reason_format CHECK (
    reason IS NULL
    OR reason ~ '^[a-z][a-z0-9_]{1,63}$'
  )
);


COMMENT ON TABLE public.auth_activity_events IS 'Server-recorded sign-in outcomes for the internal developer dashboard. Append-only, service-role only.';


CREATE INDEX IF NOT EXISTS auth_activity_events_created_idx ON public.auth_activity_events (created_at DESC);


CREATE INDEX IF NOT EXISTS auth_activity_events_user_created_idx ON public.auth_activity_events (user_id, created_at DESC);


CREATE INDEX IF NOT EXISTS auth_activity_events_type_created_idx ON public.auth_activity_events (event_type, created_at DESC);


-- ---------------------------------------------------------------------------
-- app_activity_events: operations that are not already in audit_logs
--
-- Assignments are written directly by the API/server layer rather than by a
-- database function, so they need their own server-trusted event rows. Leave,
-- role, class, and verification changes already call record_audit().
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.app_activity_events (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  actor_id uuid REFERENCES auth.users (id) ON DELETE SET NULL,
  event_type text NOT NULL,
  resource_type text NOT NULL,
  resource_id uuid,
  class_id uuid REFERENCES public.classes (id) ON DELETE SET NULL,
  metadata jsonb NOT NULL DEFAULT '{}'::jsonb,
  created_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT app_activity_events_type_allowed CHECK (
    event_type IN (
      'assignment_created',
      'assignment_updated',
      'assignment_deleted'
    )
  ),
  CONSTRAINT app_activity_events_resource_type_format CHECK (resource_type ~ '^[a-z][a-z0-9_]{2,63}$'),
  CONSTRAINT app_activity_events_metadata_object CHECK (jsonb_typeof(metadata) = 'object')
);


COMMENT ON TABLE public.app_activity_events IS 'Server-written activity for operations not covered by audit_logs. Append-only, service-role only.';


CREATE INDEX IF NOT EXISTS app_activity_events_created_idx ON public.app_activity_events (created_at DESC);


CREATE INDEX IF NOT EXISTS app_activity_events_actor_created_idx ON public.app_activity_events (actor_id, created_at DESC);


CREATE INDEX IF NOT EXISTS app_activity_events_type_created_idx ON public.app_activity_events (event_type, created_at DESC);


-- ---------------------------------------------------------------------------
-- app_error_events: sanitized server-error markers from instrumentation
--
-- Deliberately stores no message, stack, headers, cookies, or request body.
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.app_error_events (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  route_path text,
  method text,
  error_name text,
  error_digest text,
  created_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT app_error_events_route_length CHECK (
    route_path IS NULL
    OR char_length(route_path) <= 300
  ),
  CONSTRAINT app_error_events_method_length CHECK (
    method IS NULL
    OR char_length(method) <= 16
  ),
  CONSTRAINT app_error_events_name_length CHECK (
    error_name IS NULL
    OR char_length(error_name) <= 100
  ),
  CONSTRAINT app_error_events_digest_length CHECK (
    error_digest IS NULL
    OR char_length(error_digest) <= 100
  )
);


COMMENT ON TABLE public.app_error_events IS 'Sanitized server-error markers for the internal developer dashboard. No stack traces or request bodies.';


CREATE INDEX IF NOT EXISTS app_error_events_created_idx ON public.app_error_events (created_at DESC);


-- ---------------------------------------------------------------------------
-- Aggregate metrics
--
-- Counts run in one statement so the dashboard never paginates through Auth.
-- Total users and registrations come from auth.users, not profiles, so a
-- missing profile trigger cannot distort them.
-- ---------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION public.developer_dashboard_metrics (p_since_7 timestamptz, p_since_30 timestamptz) RETURNS TABLE (
  total_users bigint,
  registrations_7 bigint,
  registrations_30 bigint,
  sign_ins_7 bigint,
  sign_ins_30 bigint,
  active_users_7 bigint,
  active_users_30 bigint,
  total_assignments bigint
) LANGUAGE sql SECURITY DEFINER STABLE
SET
  search_path = public,
  pg_temp AS $$
SELECT
  (SELECT count(*) FROM auth.users),
  (SELECT count(*) FROM auth.users u WHERE u.created_at >= p_since_7),
  (SELECT count(*) FROM auth.users u WHERE u.created_at >= p_since_30),
  (
    SELECT count(*)
    FROM public.auth_activity_events e
    WHERE e.event_type = 'sign_in_succeeded'
      AND e.created_at >= p_since_7
  ),
  (
    SELECT count(*)
    FROM public.auth_activity_events e
    WHERE e.event_type = 'sign_in_succeeded'
      AND e.created_at >= p_since_30
  ),
  (
    SELECT count(DISTINCT e.user_id)
    FROM public.auth_activity_events e
    WHERE e.event_type = 'sign_in_succeeded'
      AND e.created_at >= p_since_7
  ),
  (
    SELECT count(DISTINCT e.user_id)
    FROM public.auth_activity_events e
    WHERE e.event_type = 'sign_in_succeeded'
      AND e.created_at >= p_since_30
  ),
  (SELECT count(*) FROM public.assignments);
$$;


COMMENT ON FUNCTION public.developer_dashboard_metrics (timestamptz, timestamptz) IS 'Aggregate counters for /developer. service_role only.';


