-- ---------------------------------------------------------------------------
-- Developer operations console
--
-- Two operational tables and two read-only inspection functions for the
-- developer console sub-pages (/developer/incidents, /developer/database).
--
-- Incident tables follow the monitoring convention: RLS enabled with no
-- policies, every privilege revoked from PUBLIC, anon, and authenticated, and
-- only the service role granted access. The service role INSERTs and UPDATEs
-- on behalf of a server-verified allowlisted developer; there is no DELETE
-- grant, so incidents are an append-and-amend record, not a discardable one.
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.developer_incidents (
  id uuid NOT NULL DEFAULT gen_random_uuid() PRIMARY KEY,
  title text NOT NULL,
  status text NOT NULL DEFAULT 'open',
  severity text NOT NULL DEFAULT 'medium',
  created_by uuid REFERENCES auth.users (id) ON DELETE SET NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_by uuid REFERENCES auth.users (id) ON DELETE SET NULL,
  updated_at timestamptz NOT NULL DEFAULT now(),
  resolved_at timestamptz,
  CONSTRAINT developer_incidents_title_length CHECK (char_length(title) BETWEEN 3 AND 160),
  CONSTRAINT developer_incidents_status_allowed CHECK (status IN ('open', 'monitoring', 'resolved')),
  CONSTRAINT developer_incidents_severity_allowed CHECK (severity IN ('low', 'medium', 'high')),
  CONSTRAINT developer_incidents_resolved_shape CHECK (
    (
      status = 'resolved'
      AND resolved_at IS NOT NULL
    )
    OR (
      status <> 'resolved'
      AND resolved_at IS NULL
    )
  )
);


COMMENT ON TABLE public.developer_incidents IS 'Operational incidents tracked by allowlisted developers. Service-role only; actors are server-verified session user IDs.';


CREATE INDEX IF NOT EXISTS developer_incidents_created_idx ON public.developer_incidents (created_at DESC);


CREATE INDEX IF NOT EXISTS developer_incidents_status_created_idx ON public.developer_incidents (status, created_at DESC);


-- ---------------------------------------------------------------------------
-- developer_incident_notes: timestamped investigation notes per incident
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.developer_incident_notes (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  incident_id uuid NOT NULL REFERENCES public.developer_incidents (id) ON DELETE CASCADE,
  body text NOT NULL,
  author_id uuid REFERENCES auth.users (id) ON DELETE SET NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT developer_incident_notes_body_length CHECK (char_length(body) BETWEEN 1 AND 2000)
);


COMMENT ON TABLE public.developer_incident_notes IS 'Investigation notes for developer incidents. Service-role only; actors are server-verified session user IDs.';


CREATE INDEX IF NOT EXISTS developer_incident_notes_incident_idx ON public.developer_incident_notes (incident_id, created_at DESC);


-- ---------------------------------------------------------------------------
-- developer_database_health: connectivity depth for /developer/database
--
-- Returns connection usage and the total size of the tables the platform
-- actually owns. pg_stat_activity rows are only visible to superusers and
-- readers of other backends, so the counts are honest about what this role
-- can see: if the counts come back empty the function reports NULL rather
-- than zero, and the UI renders "unavailable" instead of a fake number.
-- ---------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION public.developer_database_health () RETURNS jsonb LANGUAGE plpgsql STABLE SECURITY DEFINER
SET
  search_path = public,
  pg_temp AS $$
DECLARE
  v_connections jsonb;
  v_table_sizes jsonb;
  v_table_name text;
  v_size_bytes bigint;
BEGIN
  SELECT jsonb_build_object(
    'total', (
      SELECT count(*)::int
      FROM pg_stat_activity
    ),
    'active', (
      SELECT count(*)::int
      FROM pg_stat_activity
      WHERE state = 'active'
    ),
    'idle', (
      SELECT count(*)::int
      FROM pg_stat_activity
      WHERE state = 'idle'
    ),
    'max_connections', (
      SELECT setting::int
      FROM pg_settings
      WHERE name = 'max_connections'
    )
  )
  INTO v_connections;

  v_table_sizes := '[]'::jsonb;

  FOR v_table_name IN
    SELECT unnest(ARRAY[
      'profiles',
      'classes',
      'assignments',
      'leave_requests',
      'audit_logs',
      'notification_events',
      'auth_activity_events',
      'app_activity_events',
      'app_error_events',
      'developer_incidents'
    ])
  LOOP
    IF to_regclass(format('public.%I', v_table_name)) IS NULL THEN
      CONTINUE;
    END IF;

    SELECT pg_total_relation_size(format('public.%I', v_table_name))
    INTO v_size_bytes;

    IF v_size_bytes IS NOT NULL THEN
      v_table_sizes := v_table_sizes || jsonb_build_array(
        jsonb_build_object('table', v_table_name, 'bytes', v_size_bytes)
      );
    END IF;
  END LOOP;

  RETURN jsonb_build_object(
    'connections', v_connections,
    'table_sizes', v_table_sizes
  );
END;
$$;


COMMENT ON FUNCTION public.developer_database_health () IS 'Connection usage and owned-table sizes for /developer/database. service_role only.';


-- ---------------------------------------------------------------------------
-- developer_applied_migrations: applied migration list for /developer/database
--
-- Reads supabase_migrations.schema_migrations, which the Supabase CLI
-- maintains. If the schema is absent or unreadable the function returns
-- available = false and an empty list instead of throwing, so the page can
-- say "not available" honestly.
-- ---------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION public.developer_applied_migrations () RETURNS jsonb LANGUAGE plpgsql STABLE SECURITY DEFINER
SET
  search_path = public,
  pg_temp AS $$
DECLARE
  v_rows jsonb;
BEGIN
  BEGIN
    SELECT coalesce(
      jsonb_agg(
        jsonb_build_object(
          'version', version,
          'name', name,
          'applied_at', applied_at
        ) ORDER BY version DESC
      ),
      '[]'::jsonb
    )
    INTO v_rows
    FROM supabase_migrations.schema_migrations;

    RETURN jsonb_build_object('available', true, 'migrations', v_rows);
  EXCEPTION
    WHEN insufficient_privilege
      OR undefined_table
      OR invalid_schema_name THEN
      RETURN jsonb_build_object('available', false, 'migrations', '[]'::jsonb);
  END;
END;
$$;


COMMENT ON FUNCTION public.developer_applied_migrations () IS 'Applied Supabase CLI migrations for /developer/database. service_role only.';


