"use client";

import { Download, Loader2 } from "lucide-react";
import { useRouter } from "next/navigation";
import * as React from "react";

import { Alert } from "@/components/ui/alert";
import { Button } from "@/components/ui/button";
import { Input } from "@/components/ui/input";
import { Label } from "@/components/ui/label";
import { Select } from "@/components/ui/select";
import {
  LEAVE_REPORT_FORMATS,
  type LeaveReportFormat,
} from "@starstask/contracts";
import { formatLeaveDateRange } from "@starstask/shared";

import type { LeaveRequestSummary } from "@/lib/db/leave";

const FORMAT_LABELS: Record<LeaveReportFormat, string> = {
  summary: "Summary PDF (table only)",
  complete: "Complete PDF (with evidence)",
};

/**
 * Batch forwarding.
 *
 * The download is the operation: the server builds the PDF, records the
 * forwarding, and returns the file in one response. If it fails, nothing is
 * recorded and the requests stay `submitted`.
 *
 * The idempotency key is held across retries of the same attempt so a retried
 * click cannot create a second package; it is rotated after a success so the
 * next package is a genuinely new operation.
 */
export function ForwardPanel({
  classSlug,
  requests,
  defaultRecipient,
}: {
  classSlug: string;
  requests: LeaveRequestSummary[];
  defaultRecipient: string;
}) {
  const router = useRouter();
  const [selected, setSelected] = React.useState<string[]>([]);
  const [recipientName, setRecipientName] = React.useState(defaultRecipient);
  const [recipientEmail, setRecipientEmail] = React.useState("");
  const [format, setFormat] = React.useState<LeaveReportFormat>("summary");
  const [idempotencyKey, setIdempotencyKey] = React.useState(() =>
    crypto.randomUUID(),
  );
  const [busy, setBusy] = React.useState(false);
  const [error, setError] = React.useState<string | null>(null);
  const [result, setResult] = React.useState<{
    reference: string;
    missing: number;
  } | null>(null);

  function toggle(id: string) {
    setSelected((current) =>
      current.includes(id)
        ? current.filter((value) => value !== id)
        : [...current, id],
    );
  }

  async function onSubmit(event: React.FormEvent) {
    event.preventDefault();
    setError(null);
    setResult(null);

    if (selected.length === 0) {
      setError("Select at least one request to include.");
      return;
    }

    setBusy(true);

    try {
      const response = await fetch(
        `/api/classes/${classSlug}/leave-requests/forward`,
        {
          method: "POST",
          headers: { "Content-Type": "application/json" },
          body: JSON.stringify({
            requestIds: selected,
            recipientName,
            recipientEmail,
            reportFormat: format,
            idempotencyKey,
          }),
        },
      );

      if (!response.ok) {
        const payload = (await response.json().catch(() => null)) as {
          error?: { message: string };
        } | null;

        setError(payload?.error?.message ?? "Could not create the package.");
        return;
      }

      const reference =
        response.headers.get("X-Starstask-Forwarding-Reference") ?? "";
      const missing = Number(
        response.headers.get("X-Starstask-Missing-Attachments") ?? "0",
      );

      // Hand the generated bytes to the browser as a download.
      const blob = await response.blob();
      const url = URL.createObjectURL(blob);
      const anchor = document.createElement("a");
      anchor.href = url;
      anchor.download =
        response.headers
          .get("Content-Disposition")
          ?.match(/filename="([^"]+)"/)?.[1] ?? "absence-report.pdf";
      document.body.append(anchor);
      anchor.click();
      anchor.remove();
      URL.revokeObjectURL(url);

      setResult({ reference, missing });
      setSelected([]);
      // A new operation needs a new key.
      setIdempotencyKey(crypto.randomUUID());
      router.refresh();
    } finally {
      setBusy(false);
    }
  }

  return (
    <form
      onSubmit={(event) => void onSubmit(event)}
      className="grid gap-4"
    >
      {requests.length === 0 ? (
        <p className="text-muted-foreground text-sm">
          No requests are awaiting forwarding. Only submitted requests can be
          included in a package.
        </p>
      ) : (
        <fieldset className="grid gap-2">
          <legend className="text-sm font-medium">
            Include in this package
          </legend>

          <ul className="border-border max-h-80 divide-y overflow-auto rounded-xl border">
            {requests.map((request) => (
              <li
                key={request.id}
                className="flex items-start gap-3 p-3"
              >
                <input
                  type="checkbox"
                  id={`pick-${request.id}`}
                  checked={selected.includes(request.id)}
                  onChange={() => toggle(request.id)}
                  className="mt-1 h-4 w-4"
                />
                <label
                  htmlFor={`pick-${request.id}`}
                  className="min-w-0 flex-1 cursor-pointer"
                >
                  <span className="block text-sm font-medium">
                    {request.studentName}
                  </span>
                  <span className="text-muted-foreground block font-mono text-[11px]">
                    {request.reference}
                  </span>
                  <span className="text-muted-foreground block text-xs">
                    {request.leaveStartDate && request.leaveEndDate
                      ? formatLeaveDateRange(
                          request.leaveStartDate,
                          request.leaveEndDate,
                        )
                      : "Dates missing"}{" "}
                    · {request.evidenceCount} file
                    {request.evidenceCount === 1 ? "" : "s"}
                  </span>
                </label>
              </li>
            ))}
          </ul>
        </fieldset>
      )}

      <div className="grid gap-4 sm:grid-cols-2">
        <div>
          <Label htmlFor="recipientName">Lecturer</Label>
          <Input
            id="recipientName"
            value={recipientName}
            onChange={(event) => setRecipientName(event.target.value)}
            className="mt-1"
            placeholder="Name of the intended recipient"
            required
          />
        </div>

        <div>
          <Label htmlFor="recipientEmail">
            Lecturer email{" "}
            <span className="text-muted-foreground font-normal">
              (optional)
            </span>
          </Label>
          <Input
            id="recipientEmail"
            type="email"
            value={recipientEmail}
            onChange={(event) => setRecipientEmail(event.target.value)}
            className="mt-1"
            placeholder="Recorded for the audit trail only"
          />
        </div>
      </div>

      <div>
        <Label htmlFor="reportFormat">Report format</Label>
        <Select
          id="reportFormat"
          value={format}
          onChange={(event) =>
            setFormat(event.target.value as LeaveReportFormat)
          }
          className="mt-1"
        >
          {LEAVE_REPORT_FORMATS.map((value) => (
            <option
              key={value}
              value={value}
            >
              {FORMAT_LABELS[value]}
            </option>
          ))}
        </Select>
      </div>

      {error ? (
        <Alert variant="error">
          <p>{error}</p>
        </Alert>
      ) : null}

      {result ? (
        <Alert variant={result.missing > 0 ? "warning" : "success"}>
          <p className="font-medium">
            Package {result.reference} created with{" "}
            {selected.length || "the selected"} request(s).
          </p>
          <p className="mt-1 text-sm">
            The file was downloaded to your device. StarsTask did not email it,
            and the lecturer has not confirmed receipt.
            {result.missing > 0
              ? ` ${result.missing} attachment(s) could not be included — see the last page of the PDF.`
              : ""}
          </p>
        </Alert>
      ) : null}

      <div className="flex flex-wrap items-center gap-2">
        <Button
          type="submit"
          disabled={busy || requests.length === 0}
        >
          {busy ? (
            <Loader2
              aria-hidden="true"
              className="h-4 w-4 animate-spin"
            />
          ) : (
            <Download
              aria-hidden="true"
              className="h-4 w-4"
            />
          )}
          Generate and download
        </Button>
        <span className="text-muted-foreground text-xs">
          {selected.length} selected
        </span>
      </div>

      <p className="text-muted-foreground text-xs">
        Generating a package marks the included requests as forwarded. It does
        not approve the absence and does not mean the lecturer received it.
      </p>
    </form>
  );
}
