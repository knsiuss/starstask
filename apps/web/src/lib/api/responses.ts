import "server-only";

import { ApiError } from "@/lib/api/errors";
import {
  getErrorDigest,
  recordErrorActivity,
} from "@/lib/observability/events";

export type ApiErrorBody = {
  error: {
    code: string;
    message: string;
    fieldErrors?: Record<string, string>;
  };
};

export function apiSuccess<T>(data: T, status = 200): Response {
  return Response.json(
    { data },
    {
      status,
      headers: { "Cache-Control": "no-store" },
    },
  );
}

/** Public, non-user-specific payload; safe for a short shared cache. */
export function publicJson<T>(data: T, maxAgeSeconds = 60): Response {
  return Response.json(
    { data },
    {
      status: 200,
      headers: {
        "Cache-Control": `public, s-maxage=${maxAgeSeconds}, stale-while-revalidate=300`,
      },
    },
  );
}

/**
 * Streams generated bytes as a download.
 *
 * The filename is always produced by a server-side builder, never taken from the
 * request, so `Content-Disposition` cannot be injected. `no-store` keeps a
 * medical report out of shared caches.
 */
export function fileDownload(
  bytes: Uint8Array,
  filename: string,
  contentType: string,
): Response {
  const body = new Uint8Array(bytes);
  // Defense in depth: strip quotes and control characters so the header can
  // never split, even if a future caller changes.
  const safeFilename = filename.replace(/["\r\n]/g, "");
  const encoded = encodeURIComponent(safeFilename);

  return new Response(body, {
    status: 200,
    headers: {
      "Content-Type": contentType,
      "Content-Disposition": `attachment; filename="${safeFilename}"; filename*=UTF-8''${encoded}`,
      "Content-Length": String(body.byteLength),
      "Cache-Control": "no-store",
    },
  });
}

export function apiError(
  status: number,
  code: string,
  message: string,
  fieldErrors?: Record<string, string>,
): Response {
  const body: ApiErrorBody = {
    error: {
      code,
      message,
      ...(fieldErrors ? { fieldErrors } : {}),
    },
  };

  return Response.json(body, {
    status,
    headers: { "Cache-Control": "no-store" },
  });
}

/**
 * Converts thrown errors into a safe HTTP response. Unexpected errors are
 * logged without tokens, cookies, or request bodies, and the client only sees a
 * generic message.
 */
export async function handleRouteError(error: unknown): Promise<Response> {
  if (error instanceof ApiError) {
    return apiError(error.status, error.code, error.message, error.fieldErrors);
  }

  if (error instanceof SyntaxError) {
    return apiError(400, "invalid_json", "The request body could not be read.");
  }

  // Log the error kind + digest only: raw messages can embed SQL fragments,
  // paths, or personal data, and they outlive their usefulness in logs.
  console.error("[api] unhandled error", {
    name: error instanceof Error ? error.name : typeof error,
  });

  await recordErrorActivity({
    routePath: null,
    method: null,
    errorName: error instanceof Error ? error.name : null,
    errorDigest: getErrorDigest(error),
  });

  return apiError(
    500,
    "internal_error",
    "Something went wrong. Please try again.",
  );
}
